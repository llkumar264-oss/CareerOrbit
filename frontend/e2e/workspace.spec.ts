import {test,expect} from '@playwright/test';
test('register, persist profile, configure a campaign and pause it',async({page},testInfo)=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/');
 await page.getByLabel('Professional email').fill(`browser-${testInfo.project.name}-${Date.now()}@example.com`);
 await page.getByLabel('Password',{exact:true}).fill('A-secure-browser-password-2026');
 await page.getByRole('button',{name:'Create your workspace'}).click();
 await expect(page.getByRole('heading',{name:/Your next chapter/})).toBeVisible();
 await page.getByRole('button',{name:'Complete your profile'}).click();
 await page.getByLabel('Full name',{exact:true}).fill('Browser Applicant');
 await page.getByLabel('Skills',{exact:true}).fill('Python,SQL');
 await page.getByText('I have reviewed and confirm').click();
 await page.getByRole('button',{name:'Save profile'}).click();
 await expect(page.getByRole('status').filter({hasText:'Profile saved'})).toBeVisible();
 await page.getByRole('button',{name:'New campaign'}).click();
 await page.getByLabel('Campaign name',{exact:true}).fill('Browser test internship search');
 await page.getByLabel('Role / search keywords').fill('Python data science');
 await page.getByRole('button',{name:'Bangalore',exact:true}).click();
 await page.getByRole('button',{name:'Save campaign',exact:true}).click();
 await expect(page.getByRole('dialog')).toHaveCount(0);
 if(testInfo.project.name==='mobile') await page.getByRole('button',{name:'Open navigation'}).click();
 await page.getByRole('button',{name:'Campaigns',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Browser test internship search'})).toBeVisible();
 await page.getByRole('button',{name:'Pause campaign'}).click();
 await expect(page.locator('.campaign-card .badge')).toHaveText('paused');
 await page.reload();
 await expect(page.getByRole('heading',{name:/Your next chapter, Browser/})).toBeVisible();
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth);
 expect(overflow).toBeFalsy();
 expect(errors).toEqual([]);
 await page.screenshot({path:`test-results/${testInfo.project.name}-overview.png`,fullPage:true});
 const deleted=await page.request.delete('http://localhost:8000/api/account',{headers:{Origin:'http://localhost:3000','X-CareerOrbit-Request':'1'}});
 expect(deleted.status()).toBe(200);
});
